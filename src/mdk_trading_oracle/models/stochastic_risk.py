"""Stochastic Risk Engine: GJR-GARCH-t Volatility, Filtered Historical Simulation & Calibrated Bands.

Separates *direction* (owned by the Tertip ML tournament) from *dispersion* (owned by this module).

1. Conditional Volatility (discrete-time analogue of Heston stochastic variance):
   GJR-GARCH(1,1) with Student-t innovations, fitted on close-to-close log returns of the
   corporate-action adjusted price series:
       sigma2_{t+1} = omega + (alpha + gamma * 1[r_t < 0]) * r_t^2 + beta * sigma2_t
   Captures volatility clustering, mean reversion of variance and the leverage effect.
   Falls back to RiskMetrics EWMA (lambda = 0.94) when the MLE fit fails or is non-stationary.

2. Horizon Term Structure (corrects the flat sqrt-time scaling of GBM):
       E[sigma2_{T+k}] = LR + phi^(k-1) * (sigma2_{T+1} - LR),   phi = alpha + gamma/2 + beta
       sigma_h = sqrt(sum_{k=1..n} E[sigma2_{T+k}])

3. Filtered Historical Simulation (Monte Carlo with empirical jumps, Merton-style fat tails):
   Paths are generated by bootstrapping the stock's own standardized GARCH residuals through the
   variance recursion, so gaps and limit moves are reproduced at their empirical frequency.

4. Ito-Consistent Centering:
   Simulated terminal prices are re-centred so their *mean* equals the forecast target price.
   The median then sits below the mean by the volatility drag (~ sigma_h^2 / 2).

5. Conformal Band Calibration:
   A per-horizon dispersion scale is fitted on the audited out-of-sample backtest ledgers so that
   the nominal 90% price band realizes ~90% coverage (`config/volatility_calibration.yaml`).
"""

from __future__ import annotations

import math
import zlib
from dataclasses import dataclass
from datetime import datetime
from pathlib import Path
from typing import Any

import numpy as np
import pandas as pd
import yaml

from mdk_trading_oracle.core.logger import get_logger

logger = get_logger("mdk_oracle.models.stochastic_risk")

CALIBRATION_PATH = Path.cwd() / "config" / "volatility_calibration.yaml"

GARCH_FIT_LOOKBACK = 756  # ~3 years of sessions
MIN_FIT_OBS = 250
EWMA_LAMBDA = 0.94
DEFAULT_COVERAGE = 0.90
DEFAULT_N_PATHS = 4000
STOP_SIGMA_MULT = 1.0  # adverse stop placed 1 horizon-sigma away from entry
CORPORATE_ACTION_LOG_JUMP = 25.0  # |log return| % beyond any BIST price limit -> corporate action
MAX_PERSISTENCE = 0.999

_STATE_CACHE: dict[tuple[str, str], "VolatilityState | None"] = {}
_CALIBRATION_CACHE: dict[str, Any] | None = None


@dataclass(frozen=True)
class GarchParams:
    """GJR-GARCH(1,1) parameters in percent-squared units of daily log returns."""

    omega: float
    alpha: float
    gamma: float
    beta: float
    nu: float | None
    method: str  # "GJR_GARCH_T" | "EWMA"

    @property
    def persistence(self) -> float:
        return self.alpha + 0.5 * self.gamma + self.beta

    @property
    def long_run_var(self) -> float | None:
        if self.persistence >= 1.0 or self.omega <= 0:
            return None
        return self.omega / (1.0 - self.persistence)


@dataclass
class VolatilityState:
    """Point-in-time volatility state as of the close of `as_of_date`."""

    params: GarchParams
    sigma2_next: float  # conditional variance (pct^2) of the next session's log return
    std_resid: np.ndarray  # standardized residual pool for filtered historical simulation
    n_obs: int
    as_of_date: str

    @property
    def sigma_next_pct(self) -> float:
        return math.sqrt(self.sigma2_next)


EWMA_PARAMS = GarchParams(omega=0.0, alpha=1.0 - EWMA_LAMBDA, gamma=0.0, beta=EWMA_LAMBDA, nu=None, method="EWMA")


# ── Estimation ────────────────────────────────────────────────────────────────


def compute_log_returns_pct(prices: pd.Series, drop_corporate_actions: bool = False) -> pd.Series:
    """Close-to-close log returns in percent. Optionally drop corporate-action jumps (unadjusted prices)."""
    p = prices.astype(float)
    p = p[p > 0]
    r = (np.log(p) - np.log(p.shift(1))) * 100.0
    r = r.dropna()
    if drop_corporate_actions:
        r = r[r.abs() <= CORPORATE_ACTION_LOG_JUMP]
    return r


def fit_garch_params(log_ret_pct: np.ndarray) -> GarchParams:
    """Fit zero-mean GJR-GARCH(1,1)-t by maximum likelihood, with EWMA fallback."""
    r = np.asarray(log_ret_pct, dtype=np.float64)
    r = r[np.isfinite(r)]
    if len(r) < MIN_FIT_OBS:
        return EWMA_PARAMS
    r = r - r.mean()
    try:
        from arch import arch_model

        res = arch_model(r, mean="Zero", vol="GARCH", p=1, o=1, q=1, dist="t", rescale=False).fit(
            disp="off", show_warning=False
        )
        p = res.params
        params = GarchParams(
            omega=float(p["omega"]),
            alpha=float(p["alpha[1]"]),
            gamma=float(p["gamma[1]"]),
            beta=float(p["beta[1]"]),
            nu=float(p["nu"]),
            method="GJR_GARCH_T",
        )
        valid = (
            res.convergence_flag == 0
            and all(np.isfinite([params.omega, params.alpha, params.gamma, params.beta]))
            and params.omega > 0
            and params.alpha >= 0
            and params.beta >= 0
            and params.alpha + params.gamma >= 0
            and params.persistence < MAX_PERSISTENCE
        )
        if valid:
            return params
        logger.debug(f"GJR-GARCH fit rejected (persistence={params.persistence:.4f}); using EWMA fallback.")
    except Exception as e:
        logger.debug(f"GJR-GARCH fit failed ({e}); using EWMA fallback.")
    return EWMA_PARAMS


def filter_conditional_variance(log_ret_pct: np.ndarray, params: GarchParams, init_var: float) -> np.ndarray:
    """Run the GJR recursion. Returns s2 of length len(r)+1 where s2[t] is Var(r_t | F_{t-1}); s2[-1] is next."""
    r = np.asarray(log_ret_pct, dtype=np.float64)
    s2 = np.empty(len(r) + 1, dtype=np.float64)
    s2[0] = init_var
    for t in range(len(r)):
        shock = params.alpha + (params.gamma if r[t] < 0 else 0.0)
        s2[t + 1] = params.omega + shock * r[t] * r[t] + params.beta * s2[t]
    return s2


def variance_term_structure(sigma2_next: float, params: GarchParams, n_days: int) -> np.ndarray:
    """Expected conditional variance for each of the next n sessions (mean-reverting towards long-run)."""
    lr = params.long_run_var
    if lr is None:
        return np.full(n_days, sigma2_next)
    k = np.arange(n_days)
    return lr + (params.persistence ** k) * (sigma2_next - lr)


def horizon_sigma_pct(state: VolatilityState, n_days: int) -> float:
    """Total log-return volatility (%) accumulated over an n-session horizon."""
    return float(math.sqrt(variance_term_structure(state.sigma2_next, state.params, max(1, n_days)).sum()))


def fit_volatility_state(
    log_ret_pct: pd.Series,
    as_of_date: str | None = None,
    params: GarchParams | None = None,
    resid_pool: np.ndarray | None = None,
) -> VolatilityState | None:
    """Build a point-in-time volatility state from returns up to and including `as_of_date`.

    When `params` / `resid_pool` are supplied they are held fixed (used for zero-leakage calibration,
    where parameters are estimated strictly before the evaluation window and only filtered forward).
    """
    r = log_ret_pct.dropna()
    if len(r) < 30:
        return None
    window = r.iloc[-GARCH_FIT_LOOKBACK:]
    vals = window.to_numpy(dtype=np.float64)
    vals = vals - vals.mean()
    if params is None:
        params = fit_garch_params(vals)
    init_var = float(np.var(vals[: min(60, len(vals))])) or float(np.var(vals))
    s2 = filter_conditional_variance(vals, params, init_var)
    if resid_pool is None:
        z = vals / np.sqrt(np.maximum(s2[:-1], 1e-12))
        z = z[np.isfinite(z)]
        resid_pool = (z - z.mean()) / (z.std() or 1.0)
    as_of = as_of_date or str(r.index[-1])[:10]
    return VolatilityState(
        params=params,
        sigma2_next=float(max(s2[-1], 1e-6)),
        std_resid=resid_pool,
        n_obs=len(vals),
        as_of_date=as_of,
    )


def load_adjusted_log_returns(db: Any, symbol: str, as_of_date: str | None = None) -> pd.Series:
    """Load corporate-action adjusted close-to-close log returns (%) up to `as_of_date` inclusive."""
    sql = """
        SELECT trade_date, COALESCE(adj_close_price, close_price) AS px
        FROM silver_daily_stock_summary
        WHERE symbol = %s {date_filter}
        ORDER BY trade_date ASC;
    """
    if as_of_date:
        cur = db.execute(sql.format(date_filter="AND trade_date <= %s"), (symbol.upper(), as_of_date))
    else:
        cur = db.execute(sql.format(date_filter=""), (symbol.upper(),))
    rows = cur.fetchall()
    if not rows:
        return pd.Series(dtype=float)
    s = pd.Series([float(x[1]) if x[1] is not None else np.nan for x in rows], index=[str(x[0])[:10] for x in rows])
    return compute_log_returns_pct(s)


def get_volatility_state(db: Any, symbol: str, as_of_date: str | None = None) -> VolatilityState | None:
    """Point-in-time volatility state for a symbol, cached per (symbol, as_of_date).

    Without an `as_of_date` the state is fitted on all available sessions and not cached, since new
    sessions may arrive while a long-running API process holds the cache.
    """
    key = (symbol.upper(), str(as_of_date)[:10]) if as_of_date else None
    if key is not None and key in _STATE_CACHE:
        return _STATE_CACHE[key]
    try:
        state = fit_volatility_state(load_adjusted_log_returns(db, symbol, key[1] if key else None), as_of_date)
    except Exception as e:
        logger.warning(f"Volatility state for {symbol} failed: {e}")
        state = None
    if key is not None:
        _STATE_CACHE[key] = state
    return state


def volatility_state_from_prices(close_prices: pd.Series, as_of_date: str | None = None) -> VolatilityState | None:
    """Fallback state from an unadjusted close series (corporate-action jumps are removed)."""
    return fit_volatility_state(compute_log_returns_pct(close_prices, drop_corporate_actions=True), as_of_date)


def clear_volatility_cache() -> None:
    global _CALIBRATION_CACHE
    _STATE_CACHE.clear()
    _CALIBRATION_CACHE = None


# ── Simulation ────────────────────────────────────────────────────────────────


def simulate_log_paths(
    state: VolatilityState,
    n_days: int,
    n_paths: int = DEFAULT_N_PATHS,
    rng: np.random.Generator | None = None,
) -> np.ndarray:
    """Filtered historical simulation. Returns cumulative zero-drift log-return paths (%) of shape (n_paths, n_days)."""
    rng = rng or np.random.default_rng(0)
    p = state.params
    z = rng.choice(state.std_resid, size=(n_paths, n_days), replace=True)
    s2 = np.full(n_paths, state.sigma2_next)
    cum = np.zeros((n_paths, n_days))
    level = np.zeros(n_paths)
    for k in range(n_days):
        eps = np.sqrt(s2) * z[:, k]
        level = level + eps
        cum[:, k] = level
        s2 = p.omega + (p.alpha + p.gamma * (eps < 0)) * eps * eps + p.beta * s2
    return cum


def _seed(*parts: Any) -> int:
    return zlib.crc32("|".join(str(x) for x in parts).encode("utf-8"))


def _center_gross_paths(log_paths: np.ndarray, expected_return_pct: float, scale: float) -> np.ndarray:
    """Scale dispersion and re-centre so the terminal mean gross return equals 1 + expected return."""
    n_days = log_paths.shape[1]
    gross = np.exp(scale * log_paths / 100.0)
    drift = math.log(max(1e-6, 1.0 + expected_return_pct / 100.0) / float(gross[:, -1].mean()))
    return gross * np.exp(drift * np.arange(1, n_days + 1) / n_days)


def build_forecast_distribution(
    current_price: float,
    expected_return_pct: float,
    state: VolatilityState | None,
    n_days: int,
    deadband_pct: float,
    coverage: float = DEFAULT_COVERAGE,
    band_scale: float | None = None,
    center_shrinkage: float | None = None,
    n_paths: int = DEFAULT_N_PATHS,
    seed_key: str = "",
) -> dict[str, Any] | None:
    """Simulate the forecast distribution and derive trader risk metrics.

    The distribution is centred on `center_shrinkage * expected_return_pct`, the share of predicted magnitude that
    has historically been realized out-of-sample, so probabilities are not inflated by over-sized point forecasts.
    Target/stop first-passage odds are still measured against the ML target price.
    All probabilities are evaluated on session closing prices.
    """
    if state is None or current_price <= 0:
        return None
    n_days = max(1, int(n_days))
    scale = float(band_scale if band_scale is not None else get_band_scale(n_days))
    kappa = float(center_shrinkage if center_shrinkage is not None else get_center_shrinkage(n_days))
    center_ret = kappa * expected_return_pct
    rng = np.random.default_rng(_seed(seed_key, state.as_of_date, n_days))
    gross = _center_gross_paths(simulate_log_paths(state, n_days, n_paths, rng), center_ret, scale)
    term_ret = (gross[:, -1] - 1.0) * 100.0

    lo_q, hi_q = (1.0 - coverage) / 2.0, (1.0 + coverage) / 2.0
    ret_lo, ret_med, ret_hi = np.quantile(term_ret, [lo_q, 0.5, hi_q])
    sigma_h = horizon_sigma_pct(state, n_days) * scale

    if expected_return_pct > deadband_pct:
        side = "LONG"
    elif expected_return_pct < -deadband_pct:
        side = "SHORT"
    else:
        side = "FLAT"

    target_price = current_price * (1.0 + expected_return_pct / 100.0)
    p_target_first = p_stop_first = None
    stop_price = None
    if side != "FLAT":
        sign = 1.0 if side == "LONG" else -1.0
        stop_gross = math.exp(-sign * STOP_SIGMA_MULT * sigma_h / 100.0)
        stop_price = current_price * stop_gross
        tgt_gross = 1.0 + expected_return_pct / 100.0
        hit_t = (gross * sign >= tgt_gross * sign)
        hit_s = (gross * sign <= stop_gross * sign)
        never = n_days + 1
        t_first = np.where(hit_t.any(axis=1), hit_t.argmax(axis=1), never)
        s_first = np.where(hit_s.any(axis=1), hit_s.argmax(axis=1), never)
        p_target_first = float(np.mean((t_first < never) & (t_first < s_first)) * 100.0)
        p_stop_first = float(np.mean((s_first < never) & (s_first <= t_first)) * 100.0)

    # Expected shortfall (95%) for the side carrying the position (long by default when flat)
    if side == "SHORT":
        tail = term_ret[term_ret >= np.quantile(term_ret, 0.95)]
        es_95 = float(tail.mean())
    else:
        tail = term_ret[term_ret <= np.quantile(term_ret, 0.05)]
        es_95 = float(-tail.mean())

    return {
        "horizon_days": n_days,
        "coverage_pct": round(coverage * 100.0, 1),
        "price_low": round(current_price * (1.0 + ret_lo / 100.0), 2),
        "price_high": round(current_price * (1.0 + ret_hi / 100.0), 2),
        "median_price": round(current_price * (1.0 + ret_med / 100.0), 2),
        "target_price": round(target_price, 2),
        "risk_center_return_pct": round(center_ret, 2),
        "center_shrinkage": round(kappa, 4),
        "return_low_pct": round(float(ret_lo), 2),
        "return_high_pct": round(float(ret_hi), 2),
        "median_return_pct": round(float(ret_med), 2),
        "p_up_pct": round(float(np.mean(term_ret > deadband_pct) * 100.0), 1),
        "p_down_pct": round(float(np.mean(term_ret < -deadband_pct) * 100.0), 1),
        "p_flat_pct": round(float(np.mean(np.abs(term_ret) <= deadband_pct) * 100.0), 1),
        "position_side": side,
        "stop_price": round(stop_price, 2) if stop_price is not None else None,
        "p_target_before_stop_pct": round(p_target_first, 1) if p_target_first is not None else None,
        "p_stop_before_target_pct": round(p_stop_first, 1) if p_stop_first is not None else None,
        "expected_shortfall_95_pct": round(es_95, 2),
        "sigma_next_session_pct": round(state.sigma_next_pct * scale, 2),
        "sigma_horizon_pct": round(sigma_h, 2),
        "band_scale": round(scale, 3),
        "vol_method": state.params.method,
        "garch_persistence": round(state.params.persistence, 4),
        "student_t_nu": round(state.params.nu, 2) if state.params.nu else None,
    }


def legacy_band(target_price: float, sigma_pct: float) -> tuple[float, float]:
    """Previous symmetric Gaussian band (kept only for fallback when no volatility state is available)."""
    return target_price * (1.0 - 1.645 * sigma_pct / 100.0), target_price * (1.0 + 1.645 * sigma_pct / 100.0)


# ── Calibration ───────────────────────────────────────────────────────────────


def load_band_calibration() -> dict[str, Any]:
    global _CALIBRATION_CACHE
    if _CALIBRATION_CACHE is None:
        try:
            with open(CALIBRATION_PATH, "r", encoding="utf-8") as f:
                _CALIBRATION_CACHE = yaml.safe_load(f) or {}
        except FileNotFoundError:
            _CALIBRATION_CACHE = {}
        except Exception as e:
            logger.warning(f"Failed to read {CALIBRATION_PATH}: {e}")
            _CALIBRATION_CACHE = {}
    return _CALIBRATION_CACHE


def _horizon_calibration(n_days: int) -> dict[str, Any]:
    entry = (load_band_calibration().get("horizons", {}) or {}).get(f"{int(n_days)}d")
    return entry if isinstance(entry, dict) else {}


def get_band_scale(n_days: int) -> float:
    """Conformal dispersion scale for an n-session horizon (1.0 when uncalibrated)."""
    return float(_horizon_calibration(n_days).get("scale") or 1.0)


def get_center_shrinkage(n_days: int) -> float:
    """Out-of-sample slope of realized on predicted return; centres the risk distribution (1.0 when uncalibrated)."""
    value = _horizon_calibration(n_days).get("center_shrinkage")
    return float(value) if value is not None else 1.0


SCALE_GRID = np.round(np.arange(0.50, 2.505, 0.01), 2)
QUANTILE_GRID = np.linspace(0.0, 1.0, 201)


def scale_index(scale: float) -> int:
    return int(np.argmin(np.abs(SCALE_GRID - scale)))


def _interp_quantile(q: np.ndarray, level: float) -> np.ndarray:
    pos = level * (q.shape[1] - 1)
    i0 = int(math.floor(pos))
    i1 = min(i0 + 1, q.shape[1] - 1)
    w = pos - i0
    return q[:, i0] * (1.0 - w) + q[:, i1] * w


def inclusion_matrix(q: np.ndarray, center_pct: np.ndarray, realized_pct: np.ndarray, coverage: float) -> np.ndarray:
    """Band inclusion of realized returns for every scale in SCALE_GRID.

    `q` holds per-row quantiles (QUANTILE_GRID) of zero-drift terminal log returns (%). The band for scale c is
    the coverage interval of c * q, re-centred so the terminal mean gross return equals 1 + center.
    Returns a boolean matrix of shape (rows, len(SCALE_GRID)).
    """
    q = np.asarray(q, dtype=np.float64) / 100.0
    lo_q = _interp_quantile(q, (1.0 - coverage) / 2.0)
    hi_q = _interp_quantile(q, (1.0 + coverage) / 2.0)
    log_center = np.log(np.maximum(1e-6, 1.0 + np.asarray(center_pct) / 100.0))
    realized = np.log(np.maximum(1e-6, 1.0 + np.asarray(realized_pct) / 100.0))
    out = np.empty((len(q), len(SCALE_GRID)), dtype=bool)
    for j, c in enumerate(SCALE_GRID):
        log_mean = np.log(np.mean(np.exp(c * q), axis=1))
        out[:, j] = (realized >= log_center - log_mean + c * lo_q) & (realized <= log_center - log_mean + c * hi_q)
    return out


def fit_scale_for_coverage(inclusion: np.ndarray, coverage: float) -> float:
    """Smallest scale whose pooled realized coverage reaches the nominal target."""
    cov = inclusion.mean(axis=0)
    ok = np.where(cov >= coverage)[0]
    return float(SCALE_GRID[ok[0]] if len(ok) else SCALE_GRID[-1])


def fit_center_shrinkage(pred_pct: np.ndarray, realized_pct: np.ndarray) -> float:
    """Through-origin OLS slope of realized on predicted returns, bounded to [0, 1].

    Measures how much of a predicted magnitude is realized on average out-of-sample. A value near 0
    means the forecast magnitude carries no information about the terminal price level.
    """
    p = np.asarray(pred_pct, dtype=np.float64)
    r = np.asarray(realized_pct, dtype=np.float64)
    denom = float(np.sum(p * p))
    if denom <= 0:
        return 0.0
    return float(min(1.0, max(0.0, np.sum(p * r) / denom)))


def directional_reliability(
    q: np.ndarray,
    pred_pct: np.ndarray,
    kappa: float,
    scale: float,
    realized_pct: np.ndarray,
    deadband_pct: np.ndarray,
) -> tuple[float, float]:
    """Mean model-implied P(move beyond deadband in predicted direction) vs realized frequency (%)."""
    pred = np.asarray(pred_pct, dtype=np.float64)
    db = np.asarray(deadband_pct, dtype=np.float64)
    mask = np.abs(pred) > db
    if not mask.any():
        return float("nan"), float("nan")
    gross = np.exp(scale * np.asarray(q)[mask] / 100.0)
    gross = gross * ((1.0 + kappa * pred[mask] / 100.0) / gross.mean(axis=1))[:, None]
    tr = (gross - 1.0) * 100.0
    up = pred[mask] > 0
    p_model = np.where(up, (tr > db[mask, None]).mean(axis=1), (tr < -db[mask, None]).mean(axis=1))
    realized = np.asarray(realized_pct)[mask]
    hit = np.where(up, realized > db[mask], realized < -db[mask])
    return float(p_model.mean() * 100.0), float(hit.mean() * 100.0)


def write_band_calibration(result: dict[str, Any], path: Path | None = None) -> Path:
    path = path or CALIBRATION_PATH
    payload = {
        "generated_at": datetime.now().strftime("%Y-%m-%d %H:%M:%S"),
        "method": "GJR_GARCH_T_FHS_CONFORMAL",
        **result,
    }
    with open(path, "w", encoding="utf-8") as f:
        yaml.safe_dump(payload, f, sort_keys=False)
    clear_volatility_cache()
    return path
