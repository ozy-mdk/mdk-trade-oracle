                "    FROM broker_buys b\n",
                "    FULL OUTER JOIN broker_sells s ON b.broker_id = s.broker_id\n",
                "    LEFT JOIN bronze_brokers ref ON COALESCE(b.broker_id, s.broker_id) = ref.broker_id\n",
